export function getProductsByCategory(catSlug) {
  return PRODUCTS.filter((p) => p.category === catSlug);
}
export function getProductsByCollection(colSlug) {
  return PRODUCTS.filter((p) => p.collection === colSlug);
}
export function getProduct(slug) {
  return PRODUCTS.find((p) => p.slug === slug);
}
export function searchProducts(q) {
  const s = (q || "").toLowerCase().trim();
  if (!s) return [];
  return PRODUCTS.filter(
    (p) =>
      p.name.toLowerCase().includes(s) ||
      p.category.toLowerCase().includes(s) ||
      p.collection.replace("-", " ").toLowerCase().includes(s)
  );
}
